"""## 6. Preprocesamiento de texto

- Minúsculas: reduce la dimensionalidad del vocabulario. 'Diabetes' y 'diabetes' son la misma palabra.
- Eliminación de números: valores como '67 años' o 'V1-V4' son sustituidos por espacios. En textos clínicos los números son frecuentes pero raramente aportan información de diagnóstico.
- Limpieza de caracteres especiales: se conservan letras del español (incluyendo acentos y ñ) y se eliminan signos de puntuación, símbolos médicos, etc.
"""

import re

def preprocesar_texto(texto):
    """Limpieza básica del texto clínico en español."""
    # Minúsculas
    texto = texto.lower()
    # Eliminar números puros y caracteres especiales
    texto = re.sub(r'\d+', ' ', texto)
    # Eliminar caracteres no alfanuméricos (excepto espacios y acentos)
    texto = re.sub(r'[^a-záéíóúüñ\s]', ' ', texto)
    # Colapsar espacios múltiples
    texto = re.sub(r'\s+', ' ', texto).strip()
    return texto

df_train['texto_limpio'] = df_train['texto'].apply(preprocesar_texto)
df_dev['texto_limpio']   = df_dev['texto'].apply(preprocesar_texto)

