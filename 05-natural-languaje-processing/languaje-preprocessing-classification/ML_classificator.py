"""## 9. Entrenamiento del clasificador

Usamos **LinearSVC** envuelto en `OneVsRestClassifier` para clasificación multilabel.

- `LinearSVC` es eficiente con datos dispersos (sparse matrices) como los producidos por CountVectorizer.
- `OneVsRestClassifier` entrena un clasificador binario por cada código CIE-10.


### LinearSVC + OneVsRestClassifier
Esta estrategia entrena un clasificador binario independiente por cada código CIE-10 posible. Para un código como 'E11.9' (diabetes mellitus tipo 2), el clasificador aprende a responder: '¿este documento describe diabetes tipo 2, sí o no?'

¿Por qué LinearSVC?

- Eficiencia con datos dispersos: trabaja directamente con matrices sparse, lo que lo hace muy rápido.
- Interpretabilidad: los pesos del modelo se pueden inspeccionar para ver qué palabras son más predictivas de cada código.
- Buen desempeño en clasificación de textos: históricamente competitivo con modelos más complejos en tareas de clasificación de texto con características simples.
- n_jobs=-1: entrena los clasificadores de cada clase en paralelo usando todos los núcleos del CPU disponibles en Colab.

"""

from sklearn.multiclass import OneVsRestClassifier
from sklearn.svm import LinearSVC
from sklearn.pipeline import Pipeline
import time

clasificador = OneVsRestClassifier(
    LinearSVC(C=1.0, max_iter=2000, dual=True),
    n_jobs=-1  # usar todos los núcleos disponibles
)

print("Entrenando el clasificador...")
t0 = time.time()
clasificador.fit(X_train, y_train)
t1 = time.time()
print(f"Entrenamiento completado en {t1 - t0:.1f} segundos.")

"""## 10. Evaluación del modelo

Métricas estándar para clasificación multilabel:
- **F1 micro**: promedia por instancia, sensible a clases frecuentes.
- **F1 macro**: promedia por clase (penaliza clases raras).
- **Precision / Recall micro**
"""

from sklearn.metrics import (
    f1_score, precision_score, recall_score,
    classification_report
)

y_pred = clasificador.predict(X_dev)

f1_micro   = f1_score(y_dev, y_pred, average='micro', zero_division=0)
f1_macro   = f1_score(y_dev, y_pred, average='macro', zero_division=0)
prec_micro = precision_score(y_dev, y_pred, average='micro', zero_division=0)
rec_micro  = recall_score(y_dev, y_pred, average='micro', zero_division=0)

print("=" * 50)
print("RESULTADOS EN EL CONJUNTO DE DESARROLLO (dev)")
print("=" * 50)
print(f"F1 micro:        {f1_micro:.4f}")
print(f"F1 macro:        {f1_macro:.4f}")
print(f"Precision micro: {prec_micro:.4f}")
print(f"Recall micro:    {rec_micro:.4f}")

"""## Interpretación

- **Precision micro:** 0.6974 → el modelo es bastante cuidadoso. Cuando el modelo decide asignar un código, acierta el 70% de las veces. Es decir, de cada 10 códigos que predice, 7 son correctos. El modelo no "dispara a lo loco".
- **Recall micro:** 0.0618 → el modelo es muy tímido. De todos los códigos que deberían estar asignados en el dev, el modelo solo encuentra el 6%. Es decir, se pierde el 94% de los diagnósticos reales. El modelo casi no predice nada.
- **F1 micro:** 0.1136 → consecuencia directa del recall bajísimo.
El F1 es el promedio armónico entre precision y recall. Con un recall de 6%, aunque la precision sea 70%, el F1 queda arrastrado hacia abajo.
- **F1 macro: 0.0079** → la mayoría de los códigos nunca se predicen.
El F1 macro promedia el F1 de cada código por separado. Que sea casi 0 significa que para la gran mayoría de los ~1100 códigos únicos, el modelo predice 0 veces, entonces su F1 individual es 0. Solo unos pocos códigos muy frecuentes tienen F1 > 0.

El diagnóstico global: el modelo es muy conservador
El problema clásico con LinearSVC + OneVsRestClassifier en datasets pequeños y con muchas clases es que el umbral de decisión (score > 0) resulta demasiado exigente. El modelo aprende a ser cauteloso porque con 500 documentos de entrenamiento y 1100 clases posibles, la mayoría de los códigos aparecen muy pocas veces.


*Debido a que el modelo es tan conservador podríamos disminuir el umbral del clasificador, aumentando el recall y disminuyendo la precisión.*
"""

# Reporte por clase (solo top-30 más frecuentes en dev para legibilidad)
