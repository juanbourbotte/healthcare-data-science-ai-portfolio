"""## 7. Vectorización con [CountVectorizer](https://scikit-learn.org/stable/modules/generated/sklearn.feature_extraction.text.CountVectorizer.html)

### El concepto de `Bag of Words`
El modelo de bolsa de palabras (Bag of Words, BoW) es la representación más simple de texto para modelos de ML clásicos. Cada documento se convierte en un vector de dimensión igual al tamaño del vocabulario, donde cada posición indica cuántas veces aparece esa palabra en ese documento. La secuencia y la gramática se pierden por completo, pero la frecuencia de los términos clínicos resulta altamente informativa.
En la notebook se usa scikit-learn con los siguientes parámetros:

- `ngram_range=(1, 2)`: unigramas y bigramas
- `min_df=2`: elimina términos que aparecen en menos de 2 documentos
- `max_features=50000`: limita el vocabulario
"""

from sklearn.feature_extraction.text import CountVectorizer

vectorizer = CountVectorizer(
    ngram_range=(1, 2),
    min_df=2,
    max_features=50_000,
    strip_accents=None,        # conservamos acentos del español
    analyzer='word',
    token_pattern=r'[a-záéíóúüñ]{2,}',  # solo palabras con ≥2 letras en español

)

X_train = vectorizer.fit_transform(df_train['texto_limpio'])
X_dev   = vectorizer.transform(df_dev['texto_limpio'])

print(f"Tamaño de la matriz de train: {X_train.shape}")
print(f"Tamaño de la matriz de dev:   {X_dev.shape}")
print(f"Vocabulario aprendido:        {len(vectorizer.vocabulary_)} términos")

"""### La matriz dispersa (sparse matrix)
`CountVectorizer` devuelve una matriz dispersa (tipo scipy.sparse.csr_matrix). Con 500 documentos, una matriz densa ocuparía ~200 MB. Dado que cada documento usa solo un pequeño subconjunto del vocabulario, la mayoría de los valores son 0. La representación dispersa almacena solo los valores no nulos, reduciendo el uso de memoria en más de 10 veces.

## 8. Binarización de etiquetas (multilabel)

Cada documento puede tener múltiples códigos CIE-10 → usamos `MultiLabelBinarizer`.

Las etiquetas de CodiEsp son listas de códigos: ['E11.9', 'I10', 'N18.9']. Para que el modelo pueda trabajar con ellas, necesitamos convertirlas a un formato matricial. El MultiLabelBinarizer crea una matriz binaria de dimensión (n_documentos, n_códigos_únicos) donde un 1 indica que ese código fue asignado al documento.
"""

from sklearn.preprocessing import MultiLabelBinarizer

