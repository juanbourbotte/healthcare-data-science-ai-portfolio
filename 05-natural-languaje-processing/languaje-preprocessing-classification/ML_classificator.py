"""Un documento con 27 códigos reales y 0 predichos es un caso extremo. Probablemente sea una revisión bibliográfica que lista muchas enfermedades sin que ninguna sea el diagnóstico principal del texto.

## 12. Predicción sobre texto nuevo

Dado un texto clínico arbitrario, el pipeline predice los códigos CIE-10 más probables.

La notebook usa decision_function en lugar de predict. Esta función devuelve para cada clase una puntuación de decisión (score) en lugar de solo 0/1. Un score positivo indica que el modelo tiende a predecir esa clase. Al ordenar las clases por score descendente, obtenemos un ranking de confianza de los diagnósticos.
Con el texto de ejemplo de la notebook:


`Texto: 'Paciente de 67 años con diabetes mellitus tipo 2 e hipertensión arterial.Infarto agudo de miocardio. ECG con elevación del segmento ST...'PREDICCIONES:Código          ScoreI10              0.4349   ← hipertensión arterial esencialE11.9            0.2159   ← diabetes mellitus tipo 2, sin complicacionesN18.9            0.0209   ← enfermedad renal crónica`


Los dos primeros códigos (I10 e E11.9) son correctamente detectados y son los dos antecedentes mencionados explícitamente en el texto. El código de infarto (I21.x) no aparece, lo que refleja la limitación de un modelo entrenado con solo 500 documentos.
"""

def predecir_codigos(texto, top_n=10):
    """
    Predice los códigos CIE-10 para un texto clínico en español.
    Retorna una lista de (código, score_decision) ordenada por confianza.
    """
    texto_limpio = preprocesar_texto(texto)
    X = vectorizer.transform([texto_limpio])

    # Scores de decisión por clase
    scores = clasificador.decision_function(X)[0]

    # Ordenar de mayor a menor
    idx_ordenados = np.argsort(scores)[::-1][:top_n]
    resultados = [(mlb.classes_[i], float(scores[i])) for i in idx_ordenados if scores[i] > 0]
    #resultados = [(mlb.classes_[i], float(scores[i])) for i in idx_ordenados if scores[i] > -0.5]

    return resultados


# ── Ejemplo de uso
texto_ejemplo = """
Paciente de 67 años con antecedentes de diabetes mellitus tipo 2 e hipertensión arterial.
Acude a urgencias por dolor torácico opresivo irradiado al brazo izquierdo, de 3 horas de
evolución. ECG con elevación del segmento ST en derivaciones V1-V4. Se diagnostica infarto
agudo de miocardio con elevación del ST (IAMCEST). Se inicia fibrinólisis y se traslada a
hemodinámica para angioplastia primaria.
"""

predicciones = predecir_codigos(texto_ejemplo, top_n=10)

