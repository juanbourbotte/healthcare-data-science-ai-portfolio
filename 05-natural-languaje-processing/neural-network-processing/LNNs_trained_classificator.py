"""---
## 📐 Sección 3 — Similaridad semántica

La **similitud coseno** mide el ángulo entre dos vectores.  
Valor 1 → textos idénticos en significado. Valor 0 → sin relación. Valor -1 → opuestos.

Esto es la base de motores de búsqueda semántica, sistemas de recomendación y RAG.

"""

