"""---
## 🔢 Sección 2 — Embeddings con Sentence Transformers

### ¿Qué es un embedding?

Un **embedding** es una representación numérica densa de un texto en un espacio vectorial de alta dimensión.  
Textos con significado similar quedan "cerca" en ese espacio.

```
"El gato come pescado"  →  [0.23, -0.81, 0.04, ..., 0.67]  # vector de 384 dimensiones
"El felino se alimenta de pez"  →  [0.25, -0.79, 0.01, ..., 0.65]  # ¡muy cercano!
"El mercado de acciones subió"  →  [-0.44, 0.33, 0.88, ..., -0.12]  # muy lejano
```

Vamos a usar `sentence-transformers`, una librería que expone modelos preentrenados  
especialmente diseñados para producir embeddings de buena calidad.

"""

from sentence_transformers import SentenceTransformer

# Cargamos un modelo multilingüe liviano (~120 MB)
