# ─── Búsqueda semántica simple ───────────────────────────────────────────
def busqueda_semantica(query, corpus, model, umbral=0.3):
    """Dada una consulta, retorna las oraciones del corpus por encima del umbral de similitud."""
    query_emb = model.encode([query])
    corpus_emb = model.encode(corpus)
    sims = cosine_similarity(query_emb, corpus_emb)[0]
    indices = np.argsort(sims)[::-1]
    resultados = [(idx, sims[idx]) for idx in indices if sims[idx] >= umbral]

    print(f"\n🔍 Query: '{query}'  (umbral: {umbral})\n")
    if not resultados:
        print("  ⚠️  Ninguna oración superó el umbral.")
        return
    print(f"{'Pos':>3}  {'Similitud':>9}  Resultado")
    print("-" * 60)
    for rank, (idx, sim) in enumerate(resultados, 1):
        print(f"{rank:>3}  {sim:>9.4f}  {corpus[idx]}")

