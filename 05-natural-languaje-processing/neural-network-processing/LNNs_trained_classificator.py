def responder(pregunta: str, contexto: str, umbral: float = 0.20) -> dict:
    inputs = tokenizer(
        pregunta, contexto,
        return_tensors="pt",
        truncation=True,
        max_length=512,
        padding=True,
    )
    with torch.no_grad():
        outputs = model(**inputs)

    start = torch.argmax(outputs.start_logits)
    end   = torch.argmax(outputs.end_logits) + 1

    # Confianza aproximada: softmax del logit ganador
    conf_start = torch.softmax(outputs.start_logits, dim=-1)[0, start].item()
    conf_end   = torch.softmax(outputs.end_logits,   dim=-1)[0, end-1].item()
    confianza  = (conf_start + conf_end) / 2

    tokens    = inputs.input_ids[0][start:end]
    respuesta = tokenizer.decode(tokens, skip_special_tokens=True)

    return {
        "respuesta": respuesta,
        "confianza": confianza,
        "valida":    confianza >= umbral,
    }
