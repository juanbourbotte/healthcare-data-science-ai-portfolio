def calcular_porcentaje_correcto(y_true, cluster_labels):
    """Mapea cada cluster a la etiqueta mayoritaria del target y calcula el accuracy."""
    mapped_labels = np.zeros_like(cluster_labels)
    for cluster in np.unique(cluster_labels):
        mask = (cluster_labels == cluster)
        if mask.sum() > 0:
            # Encontrar el valor más común de y_true dentro de este cluster
            valor_mayoritario = pd.Series(y_true[mask]).mode()[0]
            mapped_labels[mask] = valor_mayoritario
    return accuracy_score(y_true, mapped_labels) * 100

