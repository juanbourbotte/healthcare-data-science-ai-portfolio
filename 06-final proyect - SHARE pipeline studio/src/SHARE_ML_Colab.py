# ============================================================
# 0. K-MEANS IMPLEMENTADO DESDE CERO
# ============================================================
class KMeansScratch:
    def __init__(self, n_clusters, max_iter=300, tol=1e-4, n_init=10, random_state=None):
        self.n_clusters = n_clusters
        self.max_iter = max_iter
        self.tol = tol
        self.n_init = n_init
        self.random_state = random_state

    def _init_centroids(self, X_numeric_array, rng): # Changed X to X_numeric_array
        n_samples = X_numeric_array.shape[0]
        # Select initial centroid from rows
        centroids = [X_numeric_array[rng.randint(n_samples)]] # Now X_numeric_array is numpy, use direct indexing
        for _ in range(1, self.n_clusters):
            # Calculate distances to existing centroids
            dist_sq = np.min(
                [np.sum((X_numeric_array - c) ** 2, axis=1) for c in centroids], axis=0 # X_numeric_array is numpy
            )
            probs = dist_sq / dist_sq.sum()
            next_idx = rng.choice(n_samples, p=probs)
            centroids.append(X_numeric_array[next_idx]) # Now X_numeric_array is numpy, use direct indexing
        return np.array(centroids)

    def _single_run(self, X_numeric_array, rng): # Changed X to X_numeric_array
        centroids = self._init_centroids(X_numeric_array, rng)
        labels = np.zeros(X_numeric_array.shape[0], dtype=int)
        for _ in range(self.max_iter):
            # Calculate distances to centroids
            dists = np.linalg.norm(X_numeric_array[:, None, :] - centroids[None, :, :], axis=2)
            labels = np.argmin(dists, axis=1)
            # Update centroids
            new_centroids = np.array([
                X_numeric_array[labels == k].mean(axis=0) if np.any(labels == k) else centroids[k]
                for k in range(self.n_clusters)
            ])
            shift = np.linalg.norm(new_centroids - centroids)
            centroids = new_centroids
            if shift < self.tol:
                break
        inertia = np.sum((X_numeric_array - centroids[labels]) ** 2)
        return centroids, labels, inertia

    def fit_predict(self, X):
        # Convert DataFrame X to a numerical numpy array once
        # This handles potential boolean columns from get_dummies by converting them to float (0.0/1.0)
        X_numeric_array = X.values.astype(float) # Ensure all data is float for numerical operations

        rng_master = np.random.RandomState(self.random_state)
        best_inertia = np.inf
        best_labels, best_centroids = None, None
        for _ in range(self.n_init):
            seed = rng_master.randint(0, 1_000_000)
            rng = np.random.RandomState(seed)
            # Pass the numerical numpy array to _single_run
            centroids, labels, inertia = self._single_run(X_numeric_array, rng)
            if inertia < best_inertia:
                best_inertia = inertia
                best_labels = labels
                best_centroids = centroids
        self.cluster_centers_ = best_centroids
        self.labels_ = best_labels
        self.inertia_ = best_inertia
        return best_labels


