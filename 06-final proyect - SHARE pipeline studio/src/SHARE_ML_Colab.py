import numpy as np
import matplotlib.pyplot as plt

# ==========================================================
# DECISION CURVE ANALYSIS (DCA)
# ==========================================================

y_true = np.asarray(y_test)
y_prob = np.asarray(test_probs)

thresholds = np.arange(0.05, 0.51, 0.01)

N = len(y_true)
prevalence = y_true.mean()

net_benefit_model = []
net_benefit_all = []

for pt in thresholds:

    pred = (y_prob >= pt).astype(int)

    TP = np.sum((pred == 1) & (y_true == 1))
    FP = np.sum((pred == 1) & (y_true == 0))

    nb_model = (TP / N) - (FP / N) * (pt / (1 - pt))
    net_benefit_model.append(nb_model)

    nb_all = prevalence - (1 - prevalence) * (pt / (1 - pt))
    net_benefit_all.append(nb_all)

plt.figure(figsize=(8,6))

plt.plot(thresholds, net_benefit_model,
         linewidth=2.5,
         label="Random Forest")

plt.plot(thresholds, net_benefit_all,
         "--",
         linewidth=2,
         label="Tratar a todos")

plt.plot(thresholds,
         np.zeros_like(thresholds),
         ":",
         linewidth=2,
         label="No tratar a nadie")

plt.xlabel("Umbral de probabilidad")
plt.ylabel("Beneficio neto")
plt.title("Decision Curve Analysis")
plt.axvline(
    x=0.35,
    color="red",
    linestyle=":",
    linewidth=2,
    label="Umbral óptimo (0.35)"
)
plt.legend()
plt.grid(alpha=0.3)

